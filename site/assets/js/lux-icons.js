  var VS16 = /\uFE0F/g;

  function svg(name, size, cls, sw) {
    var p = PATHS[name] || PATHS.sparkles || '';
    var dim = size > 0 ? ' width="' + size + '" height="' + size + '"' : '';
    return '<svg class="ico ' + (cls || '') + '"' + dim + ' viewBox="0 0 24 24"'
      + ' fill="none" stroke="currentColor" stroke-width="' + (sw || 1.8) + '"'
      + ' stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"'
      + ' focusable="false">' + p + '</svg>';
  }

  w.luxIcon = svg;

  /** Trasforma ogni emoji riconosciuto in un placeholder icona. */
  w.luxDeEmoji = function (text) {
    if (typeof text !== 'string' || !text) return text;
    var out = '', i = 0, keys = Object.keys(EMOJI).sort(function (a, b) { return b.length - a.length; });
    while (i < text.length) {
      var matched = false, cp = text.codePointAt(i), seq = String.fromCodePoint(cp);
      // prova le sequenze composte (ZWJ / FE0F) piu' lunghe prima
      for (var n = 0; n < keys.length; n++) {
        var k = keys[n];
        if (text.startsWith(k, i)) {
          out += '<i data-i=' + EMOJI[k] + ' class=ic></i>';
          i += k.length; matched = true; break;
        }
      }
      if (!matched) {
        var bare = seq.replace(VS16, '');
        if (EMOJI[bare]) {
          out += '<i data-i=' + EMOJI[bare] + ' class=ic></i>';
          i += seq.length + (text[i + seq.length] === '\uFE0F' ? 1 : 0);
        } else if (/[\u200D\uFE0F\u20E3]/.test(seq) || cp >= 0x1F000) {
          i += seq.length;           // emoji non mappato: rimosso
        } else {
          out += seq; i += seq.length;
        }
      }
    }
    return out;
  };

  /** Sostituisce i placeholder presenti in `root` con l'SVG vero. */
  w.luxUpgrade = function (root) {
    var scope = root || d;
    var list = scope.querySelectorAll ? scope.querySelectorAll('[data-i]') : [];
    for (var i = 0; i < list.length; i++) {
      var el = list[i];
      if (el.getAttribute('data-i-done')) continue;
      el.setAttribute('data-i-done', '1');
      var size = parseInt(el.getAttribute('data-s') || '0', 10) || 0;
      el.innerHTML = svg(el.getAttribute('data-i'), size, '', 1.8);
    }
  };

  function boot() {
    w.luxUpgrade(d);
    if (w.MutationObserver && !w.__luxObserver) {
      w.__luxObserver = new MutationObserver(function (muts) {
        for (var i = 0; i < muts.length; i++) {
          var nodes = muts[i].addedNodes;
          for (var j = 0; j < nodes.length; j++) {
            var n = nodes[j];
            if (!n || n.nodeType !== 1) continue;
            if (n.hasAttribute && n.hasAttribute('data-i')) w.luxUpgrade(n.parentNode || d);
            else w.luxUpgrade(n);
          }
        }
      });
      w.__luxObserver.observe(d.documentElement, { childList: true, subtree: true });
    }
  }

  if (d.readyState === 'loading') d.addEventListener('DOMContentLoaded', boot);
  else boot();
